type Level = 'el' | 'mid' | 'hi'
const levelKey = (l?: SchoolLevel): Level => (l === '초등학교' ? 'el' : l === '고등학교' ? 'hi' : 'mid')

// 받침 유무에 따라 은/는을 고른다(한글로 끝나지 않으면 '은(는)').
function eunNeun(word: string): string {
  const last = word.trim().slice(-1)
  const code = last.charCodeAt(0) - 0xac00
  if (code < 0 || code > 11171) return `${word}은(는)`
  return `${word}${code % 28 === 0 ? '는' : '은'}`
}

